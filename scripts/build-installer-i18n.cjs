'use strict';

// Build-time only: the installer needs no Node, Python, gettext or UTF-8 locale.
const fs = require('node:fs');
const path = require('node:path');
const rows = require('../src/lib/InstallerMessages.json');
const languages = ['en', 'ru', 'fa', 'es', 'zh-cn'];
const quote = (text) => `'${text.replaceAll('\n', '\\n').replaceAll("'", "'\\''")}'`;
const keys = new Set();
for (const row of rows) {
  if (row.length !== languages.length || row.some((text) => typeof text !== 'string' || !text)) {
    throw new Error('Every installer message must have all five translations');
  }
  if (keys.has(row[0])) throw new Error(`Duplicate installer message: ${row[0]}`);
  keys.add(row[0]);
  const signature = (text) => JSON.stringify(text.match(/%./g) || []);
  for (const text of row) {
    if (signature(text) !== signature(row[0]) || /%(?!s)/.test(text) || /[\r\0]/.test(text)) {
      throw new Error(`Invalid installer message format: ${row[0]}`);
    }
  }
}
const output = '#!/bin/sh\n# Generated by scripts/build-installer-i18n.cjs; edit src/lib/InstallerMessages.json.\n'
  + '# Values are literal formats. Caller data is always a separate printf argument.\n'
  + 'awg_installer_format() {\n  case "$1" in\n'
  + rows.map((row) => `    ${quote(row[0])})\n      case "\${AWG_LANG_VALUE:-en}" in\n`
    + row.slice(1).map((text, index) => `        ${languages[index + 1]}) printf '%s' ${quote(text)} ;;\n`).join('')
    + `        *) printf '%s' ${quote(row[0])} ;;\n      esac ;;\n`).join('')
  + '    *) return 1 ;;\n  esac\n}\n\n'
  + 'message() {\n  if awg_message_format=$(awg_installer_format "$1"); then\n'
  + '    shift\n    # An empty leading %s also makes formats starting with -- safe in bash.\n'
  + '    printf "%s$awg_message_format" \'\' "$@"\n'
  + '  else\n    # Unknown diagnostics remain literal, including percent signs and backslashes.\n'
  + '    printf \'%s\' "$1"\n  fi\n}\n';
const target = path.join(__dirname, '../lib/installer-i18n.sh');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) {
    throw new Error('Installer catalog is stale; run node scripts/build-installer-i18n.cjs');
  }
} else {
  fs.writeFileSync(target, output);
}
